//! Generates the Kotlin (and later Swift) bindings for `anywhere-mobile`. Run by the
//! Android build (the `:rust` module); pinned to the same UniFFI version as the library.
//!
//! After generating Kotlin it patches one thing in UniFFI's async glue (see [`patch_kotlin`]),
//! and fails the build if the glue doesn't look as expected.

use std::path::{Path, PathBuf};

fn main() {
    let args: Vec<String> = std::env::args().collect();
    uniffi::uniffi_bindgen_main();
    if let Some(out) = kotlin_out_dir(&args)
        && let Err(e) = patch_dir(&out)
    {
        eprintln!("anywhere-uniffi-bindgen: {e}");
        std::process::exit(1);
    }
}

/// The output directory of a `generate --language kotlin` run, if this is one.
fn kotlin_out_dir(args: &[String]) -> Option<PathBuf> {
    let value = |flag: &str| {
        args.iter()
            .position(|a| a == flag)
            .and_then(|i| args.get(i + 1))
    };
    let generating = args.get(1).is_some_and(|a| a == "generate");
    let kotlin = value("--language").is_some_and(|l| l == "kotlin");
    match (generating, kotlin) {
        (true, true) => value("--out-dir").map(PathBuf::from),
        _ => None,
    }
}

/// Patch every generated Kotlin file that holds the async glue: exactly one must.
fn patch_dir(dir: &Path) -> Result<(), String> {
    let mut patched = 0;
    for path in kotlin_files(dir)? {
        let src = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        if src.contains(GLUE) {
            std::fs::write(&path, patch_kotlin(&src)?)
                .map_err(|e| format!("{}: {e}", path.display()))?;
            patched += 1;
        }
    }
    match patched {
        1 => Ok(()),
        n => Err(format!(
            "expected UniFFI's async glue in one Kotlin file, found {n}"
        )),
    }
}

fn kotlin_files(dir: &Path) -> Result<Vec<PathBuf>, String> {
    let mut out = vec![];
    let entries = std::fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            out.extend(kotlin_files(&path)?);
        } else if path.extension().is_some_and(|e| e == "kt") {
            out.push(path);
        }
    }
    Ok(out)
}

/// UniFFI's driver for a Rust future, as generated by UniFFI 0.31.
const GLUE: &str = "internal suspend fun<T, F, E: kotlin.Exception> uniffiRustCallAsync(\n    \
rustFuture: Long,\n    \
pollFunc: (Long, UniffiRustFutureContinuationCallback, Long) -> Unit,\n    \
completeFunc: (Long, UniffiRustCallStatus) -> F,\n    \
freeFunc: (Long) -> Unit,\n    \
liftFunc: (F) -> T,\n    \
errorHandler: UniffiRustCallStatusErrorHandler<E>\n\
): T {\n";

const RENAMED: &str = "uniffiRustCallAsyncPolledHere(";

/// The replacement driver, appended to the file.
const DRIVER: &str = r#"
// Added by anywhere-uniffi-bindgen. UniFFI calls a future's continuation while holding that
// future's lock, and on the main thread (Dispatchers.Main.immediate) Kotlin resumes the
// waiting coroutine right there, inside the callback. When polling one future wakes another
// (both waiting on the same Rust resource, e.g. requests failing at once in airplane mode),
// the resumed coroutine polls its own future again and blocks for ever on the lock its own
// thread holds: the app freezes (ANR). Polling on Dispatchers.Default, which always
// dispatches a resumption instead of running it inline, never re-enters a held lock, and
// keeps Rust work off the main thread.
internal suspend fun<T, F, E: kotlin.Exception> uniffiRustCallAsync(
    rustFuture: Long,
    pollFunc: (Long, UniffiRustFutureContinuationCallback, Long) -> Unit,
    completeFunc: (Long, UniffiRustCallStatus) -> F,
    freeFunc: (Long) -> Unit,
    liftFunc: (F) -> T,
    errorHandler: UniffiRustCallStatusErrorHandler<E>
): T {
    var started = false
    try {
        return kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.Default) {
            started = true
            uniffiRustCallAsyncPolledHere(rustFuture, pollFunc, completeFunc, freeFunc, liftFunc, errorHandler)
        }
    } finally {
        // Cancelled before polling began: the future is still ours to free.
        if (!started) freeFunc(rustFuture)
    }
}
"#;

/// Make every Rust future be polled on `Dispatchers.Default` (see [`DRIVER`]): UniFFI's own
/// driver is renamed and wrapped. Refuses anything but exactly one copy of the glue it knows.
fn patch_kotlin(src: &str) -> Result<String, String> {
    if src.matches(GLUE).count() != 1 {
        return Err(
            "UniFFI's async glue has changed: review the patch in anywhere-uniffi-bindgen".into(),
        );
    }
    if src.contains(RENAMED) {
        return Err("bindings already patched".into());
    }
    let glue = GLUE.replacen("uniffiRustCallAsync(", RENAMED, 1);
    let mut out = src.replacen(GLUE, &glue, 1);
    out.push_str(DRIVER);
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn generated() -> String {
        format!(
            "package x\n\n{GLUE}    try {{\n        do {{ }} while (false)\n    }} finally {{\n        freeFunc(rustFuture)\n    }}\n}}\n\nsuspend fun call() = uniffiRustCallAsync(1, p, c, f, l, e)\n"
        )
    }

    #[test]
    fn the_driver_is_renamed_and_wrapped() {
        let out = patch_kotlin(&generated()).unwrap();
        // One definition of each: the wrapper keeps the name every call site uses.
        assert_eq!(
            out.matches("fun<T, F, E: kotlin.Exception> uniffiRustCallAsync(")
                .count(),
            1
        );
        assert_eq!(
            out.matches("fun<T, F, E: kotlin.Exception> uniffiRustCallAsyncPolledHere(")
                .count(),
            1
        );
        assert!(out.contains("withContext(kotlinx.coroutines.Dispatchers.Default)"));
        assert!(out.contains("uniffiRustCallAsyncPolledHere(rustFuture, pollFunc"));
        // Call sites are untouched.
        assert!(out.contains("suspend fun call() = uniffiRustCallAsync(1, p, c, f, l, e)"));
        // The wrapper follows the original (top-level functions can be in any order).
        assert!(out.find("PolledHere(\n").unwrap() < out.find(DRIVER).unwrap());
    }

    #[test]
    fn changed_or_missing_glue_fails_the_build() {
        assert!(patch_kotlin("package x\n").is_err());
        let changed =
            generated().replace("freeFunc: (Long) -> Unit", "freeFunc: (Long) -> Boolean");
        assert!(patch_kotlin(&changed).is_err());
        let twice = format!("{}{}", generated(), generated());
        assert!(patch_kotlin(&twice).is_err());
    }

    #[test]
    fn patching_twice_is_refused() {
        let once = patch_kotlin(&generated()).unwrap();
        assert!(patch_kotlin(&once).is_err());
    }

    #[test]
    fn only_kotlin_generation_is_patched() {
        let args = |s: &str| -> Vec<String> { s.split(' ').map(String::from).collect() };
        assert_eq!(
            kotlin_out_dir(&args(
                "bindgen generate --library l.so --language kotlin --no-format --out-dir /o"
            )),
            Some(PathBuf::from("/o"))
        );
        assert_eq!(
            kotlin_out_dir(&args("bindgen generate --language swift --out-dir /o")),
            None
        );
        assert_eq!(
            kotlin_out_dir(&args("bindgen scaffolding --language kotlin --out-dir /o")),
            None
        );
        assert_eq!(
            kotlin_out_dir(&args("bindgen generate --language kotlin")),
            None
        );
    }

    #[test]
    fn a_directory_needs_exactly_one_file_with_the_glue() {
        let dir =
            std::env::temp_dir().join(format!("anywhere-bindgen-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("a/b")).unwrap();
        std::fs::write(dir.join("a/other.kt"), "package y\n").unwrap();
        assert!(patch_dir(&dir).is_err(), "no glue anywhere");
        std::fs::write(dir.join("a/b/gen.kt"), generated()).unwrap();
        patch_dir(&dir).unwrap();
        let out = std::fs::read_to_string(dir.join("a/b/gen.kt")).unwrap();
        assert!(out.contains(DRIVER));
        assert!(
            patch_dir(&dir).is_err(),
            "glue renamed: nothing left to patch"
        );
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
